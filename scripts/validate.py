from pathlib import Path
from html.parser import HTMLParser
from urllib.parse import urlsplit, unquote
import re
import subprocess

root = Path(__file__).resolve().parents[1] / 'dist'
errors = []

class Page(HTMLParser):
    def __init__(self):
        super().__init__()
        self.ids, self.refs, self.text = [], [], []
        self.skip = 0

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag in ['script', 'style', 'svg']:
            self.skip += 1
        if 'id' in attrs:
            self.ids.append(attrs['id'])
        for key in ['src', 'href', 'poster']:
            if key in attrs:
                self.refs.append(attrs[key])

    def handle_endtag(self, tag):
        if tag in ['script', 'style', 'svg']:
            self.skip = max(0, self.skip - 1)

    def handle_data(self, value):
        if not self.skip:
            self.text.append(value)

for path in root.rglob('*.html'):
    page = Page()
    page.feed(path.read_text(encoding='utf-8'))
    if len(page.ids) != len(set(page.ids)):
        errors.append(f'{path.name}: duplicate IDs')
    for ref in page.refs:
        url = urlsplit(ref)
        if url.scheme or url.netloc:
            continue
        target = ((root / url.path.lstrip('/') if url.path.startswith('/') else path.parent / url.path)
                  if url.path else path)
        if target.is_dir():
            target /= 'index.html'
        if not target.exists():
            errors.append(f'{path.name}: missing {ref}')
        if target == path and url.fragment and unquote(url.fragment) not in page.ids:
            errors.append(f'{path.name}: missing anchor {ref}')
    if re.search(r'lorem ipsum|powered by (?:ai|openai|chatgpt)|made (?:with|by) (?:ai|codex|chatgpt)|generated by (?:ai|codex|chatgpt)',
                 ' '.join(page.text), re.I):
        errors.append(f'{path.name}: placeholder or generated branding')

for path in root.rglob('*.js'):
    result = subprocess.run(['node', '--check', str(path)], capture_output=True, text=True)
    if result.returncode:
        errors.append(result.stderr)

if errors:
    raise SystemExit('\n'.join(errors))
print('HTML references, anchors, IDs, branding scan and JavaScript syntax checks passed.')
